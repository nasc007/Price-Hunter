CREATE TABLE alertas (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    usuario_id BIGINT UNSIGNED NOT NULL,
    produto_id BIGINT UNSIGNED NOT NULL,
    oferta_id BIGINT UNSIGNED NULL,
    tipo ENUM('preco_desejado', 'variacao', 'sistema') NOT NULL,
    titulo VARCHAR(180) NOT NULL,
    mensagem VARCHAR(500) NOT NULL,
    preco_referencia DECIMAL(12,2) NULL,
    preco_encontrado DECIMAL(12,2) NULL,
    hash_alerta CHAR(64) NOT NULL,
    status ENUM('novo', 'lido', 'arquivado') NOT NULL DEFAULT 'novo',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_alertas_hash (hash_alerta),
    KEY idx_alertas_usuario_status (usuario_id, status, created_at),
    KEY idx_alertas_produto (produto_id),
    CONSTRAINT fk_alertas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_alertas_produto FOREIGN KEY (produto_id) REFERENCES produtos (id) ON DELETE CASCADE,
    CONSTRAINT fk_alertas_oferta FOREIGN KEY (oferta_id) REFERENCES ofertas (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE notificacoes (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    usuario_id BIGINT UNSIGNED NOT NULL,
    alerta_id BIGINT UNSIGNED NULL,
    canal ENUM('dashboard', 'email', 'whatsapp') NOT NULL,
    destino VARCHAR(190) NULL,
    assunto VARCHAR(180) NULL,
    mensagem VARCHAR(1000) NOT NULL,
    status ENUM('pendente', 'enviada', 'falha', 'ignorada') NOT NULL DEFAULT 'pendente',
    tentativas TINYINT UNSIGNED NOT NULL DEFAULT 0,
    erro VARCHAR(500) NULL,
    enviada_em DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_notificacoes_usuario (usuario_id, status, created_at),
    KEY idx_notificacoes_alerta (alerta_id),
    CONSTRAINT fk_notificacoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_notificacoes_alerta FOREIGN KEY (alerta_id) REFERENCES alertas (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE logs_execucao (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    usuario_id BIGINT UNSIGNED NULL,
    monitoramento_id BIGINT UNSIGNED NULL,
    produto_id BIGINT UNSIGNED NULL,
    marketplace_id SMALLINT UNSIGNED NULL,
    integracao_id BIGINT UNSIGNED NULL,
    tipo ENUM('cron', 'manual', 'alerta') NOT NULL,
    nivel ENUM('info', 'warning', 'error') NOT NULL DEFAULT 'info',
    mensagem VARCHAR(500) NOT NULL,
    contexto JSON NULL,
    iniciado_em DATETIME NULL,
    finalizado_em DATETIME NULL,
    duracao_ms INT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_logs_usuario (usuario_id, created_at),
    KEY idx_logs_produto (produto_id, created_at),
    KEY idx_logs_marketplace (marketplace_id, created_at),
    CONSTRAINT fk_logs_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT fk_logs_monitoramento FOREIGN KEY (monitoramento_id) REFERENCES monitoramentos (id) ON DELETE SET NULL,
    CONSTRAINT fk_logs_produto FOREIGN KEY (produto_id) REFERENCES produtos (id) ON DELETE SET NULL,
    CONSTRAINT fk_logs_marketplace FOREIGN KEY (marketplace_id) REFERENCES marketplaces (id) ON DELETE SET NULL,
    CONSTRAINT fk_logs_integracao FOREIGN KEY (integracao_id) REFERENCES integracoes (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
