CREATE TABLE usuarios (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(190) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    telefone VARCHAR(20) NULL,
    whatsapp VARCHAR(20) NULL,
    ativo TINYINT NOT NULL DEFAULT 1,
    ultimo_login_em DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_usuarios_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE marketplaces (
    id SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    codigo VARCHAR(40) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    tipo ENUM('api', 'feed', 'autorizado') NOT NULL DEFAULT 'api',
    site_url VARCHAR(255) NULL,
    ativo TINYINT NOT NULL DEFAULT 1,
    observacao VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_marketplaces_codigo (codigo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE produtos (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    usuario_id BIGINT UNSIGNED NOT NULL,
    nome VARCHAR(180) NOT NULL,
    marca VARCHAR(120) NULL,
    modelo VARCHAR(120) NULL,
    categoria VARCHAR(120) NULL,
    descricao TEXT NULL,
    sku VARCHAR(80) NULL,
    ean VARCHAR(20) NULL,
    imagem VARCHAR(255) NULL,
    palavras_chave VARCHAR(500) NULL,
    atributos JSON NULL,
    preco_desejado DECIMAL(12,2) NULL,
    valor_maximo DECIMAL(12,2) NULL,
    status ENUM('ativo', 'pausado', 'arquivado') NOT NULL DEFAULT 'ativo',
    frequencia_horas TINYINT UNSIGNED NOT NULL DEFAULT 24,
    ultima_pesquisa_em DATETIME NULL,
    proxima_pesquisa_em DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_produtos_usuario_status (usuario_id, status),
    KEY idx_produtos_proxima (proxima_pesquisa_em),
    KEY idx_produtos_categoria (usuario_id, categoria),
    KEY idx_produtos_marca (usuario_id, marca),
    CONSTRAINT fk_produtos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT chk_produtos_frequencia CHECK (frequencia_horas IN (1, 6, 12, 24))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE integracoes (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    marketplace_id SMALLINT UNSIGNED NOT NULL,
    usuario_id BIGINT UNSIGNED NULL,
    nome VARCHAR(120) NOT NULL,
    driver VARCHAR(160) NOT NULL,
    configuracao JSON NULL,
    ativo TINYINT NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_integracoes_ativas (ativo, marketplace_id),
    KEY idx_integracoes_usuario (usuario_id),
    CONSTRAINT fk_integracoes_marketplace FOREIGN KEY (marketplace_id) REFERENCES marketplaces (id),
    CONSTRAINT fk_integracoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE ofertas (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    produto_id BIGINT UNSIGNED NOT NULL,
    usuario_id BIGINT UNSIGNED NOT NULL,
    marketplace_id SMALLINT UNSIGNED NOT NULL,
    id_externo VARCHAR(120) NULL,
    titulo VARCHAR(255) NOT NULL,
    loja VARCHAR(160) NULL,
    vendedor VARCHAR(160) NULL,
    condicao ENUM('novo', 'usado', 'recondicionado', 'desconhecido') NOT NULL DEFAULT 'desconhecido',
    preco DECIMAL(12,2) NOT NULL,
    frete DECIMAL(12,2) NULL,
    frete_status ENUM('confirmado', 'gratis', 'indisponivel', 'desconhecido') NOT NULL DEFAULT 'desconhecido',
    desconto DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    preco_total DECIMAL(12,2) NULL,
    disponibilidade ENUM('disponivel', 'indisponivel', 'sob_consulta') NOT NULL DEFAULT 'disponivel',
    url VARCHAR(1000) NOT NULL,
    imagem VARCHAR(1000) NULL,
    moeda CHAR(3) NOT NULL DEFAULT 'BRL',
    hash_oferta CHAR(64) NOT NULL,
    correspondencia_score DECIMAL(5,2) NULL,
    atributos_match JSON NULL,
    ativa TINYINT NOT NULL DEFAULT 1,
    primeira_vista_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultima_vista_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_ofertas_hash (produto_id, hash_oferta),
    KEY idx_ofertas_usuario (usuario_id, ativa),
    KEY idx_ofertas_produto_total (produto_id, ativa, preco_total),
    KEY idx_ofertas_marketplace (marketplace_id),
    CONSTRAINT fk_ofertas_produto FOREIGN KEY (produto_id) REFERENCES produtos (id) ON DELETE CASCADE,
    CONSTRAINT fk_ofertas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_ofertas_marketplace FOREIGN KEY (marketplace_id) REFERENCES marketplaces (id),
    CONSTRAINT chk_ofertas_total CHECK (
        (frete_status IN ('confirmado', 'gratis') AND preco_total IS NOT NULL)
        OR (frete_status NOT IN ('confirmado', 'gratis'))
    )
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE historico_precos (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    oferta_id BIGINT UNSIGNED NULL,
    produto_id BIGINT UNSIGNED NOT NULL,
    usuario_id BIGINT UNSIGNED NOT NULL,
    marketplace_id SMALLINT UNSIGNED NOT NULL,
    loja VARCHAR(160) NULL,
    vendedor VARCHAR(160) NULL,
    preco DECIMAL(12,2) NOT NULL,
    frete DECIMAL(12,2) NULL,
    desconto DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    preco_total DECIMAL(12,2) NULL,
    frete_status ENUM('confirmado', 'gratis', 'indisponivel', 'desconhecido') NOT NULL DEFAULT 'desconhecido',
    disponibilidade ENUM('disponivel', 'indisponivel', 'sob_consulta') NOT NULL DEFAULT 'disponivel',
    consultado_em DATETIME NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_historico_produto_data (produto_id, consultado_em),
    KEY idx_historico_usuario_data (usuario_id, consultado_em),
    KEY idx_historico_oferta (oferta_id),
    CONSTRAINT fk_historico_oferta FOREIGN KEY (oferta_id) REFERENCES ofertas (id) ON DELETE SET NULL,
    CONSTRAINT fk_historico_produto FOREIGN KEY (produto_id) REFERENCES produtos (id) ON DELETE CASCADE,
    CONSTRAINT fk_historico_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_historico_marketplace FOREIGN KEY (marketplace_id) REFERENCES marketplaces (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE monitoramentos (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    produto_id BIGINT UNSIGNED NOT NULL,
    usuario_id BIGINT UNSIGNED NOT NULL,
    frequencia_horas TINYINT UNSIGNED NOT NULL DEFAULT 24,
